"""Evaluate magnetogram super-resolution predictions by sample category.

Dependencies: Python >= 3.10, NumPy >= 1.23, pandas >= 1.5,
Matplotlib >= 3.6, SciPy >= 1.9, scikit-image >= 0.19.
Random seed: 42 (the evaluation itself is deterministic).
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from constants import gt_norm, h_shape_hr, h_shape_lr, w_shape_hr, w_shape_lr
from utils_eval import (
    eval_flux,
    eval_metrics,
    get_bicubic_map,
    get_empirical_map_from_dalda2017,
    get_empirical_map_from_zhang2023,
)
from utils_load_data import load_output_sample


RANDOM_SEED = 42
MODEL_ORDER = ["PM-LTEW", "Bicubic", "Empirical-D", "Empirical-Z"]
MODEL_COLORS = {
    "PM-LTEW": "red",
    "Bicubic": "royalblue",
    "Empirical-D": "darkorange",
    "Empirical-Z": "forestgreen",
}
METRIC_ORDER = [
    "MAE_G",
    "RMSE_G",
    "RMSE_over_sigma_HR",
    "CC",
    "R2",
    "SSIM",
    "PSNR_dB",
    "net_flux_ratio",
    "unsigned_flux_ratio",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate all, heliocentric-angle, and AR/non-AR test subsets."
    )
    parser.add_argument(
        "--run-dir",
        type=Path,
        default=Path("ltew/test_20260416"),
        help="Experiment directory containing test_pred.",
    )
    parser.add_argument("--dataset-type", default="test")
    parser.add_argument(
        "--classification-file",
        type=Path,
        default=None,
        help="AR classification CSV generated by classify_test_samples_by_field.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory. Defaults to the experiment directory.",
    )
    parser.add_argument("--show", action="store_true")
    parser.add_argument("--no-save", action="store_true")
    return parser.parse_args()


def natural_key(path: Path) -> tuple[int, str]:
    match = re.search(r"sample_(\d+)", path.name)
    return (int(match.group(1)) if match else 10**12, path.name)


def finite_mean_std(values: pd.Series | np.ndarray) -> tuple[float, float]:
    array = np.asarray(values, dtype=np.float64)
    array = array[np.isfinite(array)]
    if not len(array):
        return np.nan, np.nan
    std = np.std(array, ddof=1) if len(array) > 1 else 0.0
    return float(np.mean(array)), float(std)


def safe_ratio(numerator: float, denominator: float) -> float:
    scale = max(abs(numerator), abs(denominator), 1.0)
    if not np.isfinite(denominator) or abs(denominator) <= 1e-12 * scale:
        return np.nan
    return float(numerator / denominator)


def evaluate_one(npz_path: Path) -> list[dict[str, float | int | str]]:
    inp, gt, pred, sample_idx = load_output_sample(npz_path)
    lr_map = np.squeeze(np.asarray(inp[0], dtype=np.float64))
    distance_map = np.asarray(inp[1], dtype=np.float64)
    hr_map = np.asarray(gt, dtype=np.float64).reshape((h_shape_hr, w_shape_hr)) / gt_norm
    sr_map = np.asarray(pred, dtype=np.float64).reshape((h_shape_hr, w_shape_hr))

    distance_arcsec = distance_map[h_shape_lr // 2, w_shape_lr // 2]
    theta_deg = float(np.degrees(np.arcsin(np.clip(distance_arcsec / 960.0, -1.0, 1.0))))
    hr_std = float(np.std(hr_map, ddof=0))

    maps = {
        "PM-LTEW": sr_map,
        "Bicubic": get_bicubic_map(lr_map, h_shape_hr, w_shape_hr),
    }
    maps["Empirical-D"] = get_empirical_map_from_dalda2017(maps["Bicubic"])
    maps["Empirical-Z"] = get_empirical_map_from_zhang2023(maps["Bicubic"])

    flux_net_hr, flux_unsigned_hr = eval_flux(hr_map)
    rows = []
    for model, field_map in maps.items():
        mae, rmse, cc, r2, ssim, psnr = eval_metrics(hr_map, field_map)
        flux_net, flux_unsigned = eval_flux(field_map)
        rows.append(
            {
                "prediction_file": npz_path.name,
                "sample_idx": int(sample_idx),
                "theta_deg": theta_deg,
                "model": model,
                "MAE_G": mae,
                "RMSE_G": rmse,
                "RMSE_over_sigma_HR": safe_ratio(rmse, hr_std),
                "CC": cc,
                "R2": r2,
                "SSIM": ssim,
                "PSNR_dB": psnr,
                "net_flux_ratio": safe_ratio(flux_net, flux_net_hr),
                "unsigned_flux_ratio": safe_ratio(flux_unsigned, flux_unsigned_hr),
            }
        )
    return rows


def load_classification(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Classification file not found: {path}\n"
            "Run classify_test_samples_by_field.py for the same experiment first."
        )
    table = pd.read_csv(path)
    required = {"sample_idx", "region_type"}
    missing = required.difference(table.columns)
    if missing:
        raise ValueError(f"Classification file is missing columns: {sorted(missing)}")
    if table["sample_idx"].duplicated().any():
        raise ValueError("Classification file contains duplicate sample_idx values.")
    invalid = set(table["region_type"].dropna().unique()).difference({"AR", "non-AR"})
    if invalid:
        raise ValueError(f"Unknown region_type values: {sorted(invalid)}")
    return table[["sample_idx", "region_type"]]


def make_categories(sample_table: pd.DataFrame) -> dict[str, np.ndarray]:
    theta = sample_table["theta_deg"].to_numpy(dtype=np.float64)
    region = sample_table["region_type"].to_numpy(dtype=str)
    return {
        "all": np.ones(len(sample_table), dtype=bool),
        "theta_0-30": (theta >= 0.0) & (theta < 30.0),
        "theta_30-60": (theta >= 30.0) & (theta < 60.0),
        "theta_60-90": (theta >= 60.0) & (theta <= 90.0),
        "AR": region == "AR",
        "non-AR": region == "non-AR",
    }


def build_summary_table(subset: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    numeric_rows = []
    formatted_rows = []
    for model in MODEL_ORDER:
        model_data = subset[subset["model"] == model]
        numeric_row: dict[str, float | str | int] = {
            "model": model,
            "num_samples": int(model_data["sample_idx"].nunique()),
        }
        formatted_row: dict[str, str | int] = {
            "model": model,
            "num_samples": int(model_data["sample_idx"].nunique()),
        }
        for metric in METRIC_ORDER:
            mean, std = finite_mean_std(model_data[metric])
            numeric_row[f"{metric}_mean"] = mean
            numeric_row[f"{metric}_std"] = std
            formatted_row[metric] = f"{mean:.4f} ± {std:.4f}"
        numeric_rows.append(numeric_row)
        formatted_rows.append(formatted_row)
    return pd.DataFrame(numeric_rows), pd.DataFrame(formatted_rows)


def write_text_summary(
    path: Path,
    category: str,
    num_samples: int,
    numeric_table: pd.DataFrame,
) -> None:
    lines = [
        f"Category: {category}",
        f"Number of samples: {num_samples}",
        "Values are mean ± sample standard deviation.",
        "Net-flux ratios with a near-zero HR denominator are excluded as NaN.",
        "",
    ]
    for _, row in numeric_table.iterrows():
        lines.append(f"[{row['model']}]")
        for metric in METRIC_ORDER:
            lines.append(
                f"{metric:<24s} {row[f'{metric}_mean']:.4f} ± "
                f"{row[f'{metric}_std']:.4f}"
            )
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def plot_summary(
    subset: pd.DataFrame,
    category: str,
    num_samples: int,
    output_path: Path | None,
    show: bool,
) -> None:
    titles = {
        "MAE_G": "MAE (G)",
        "RMSE_G": "RMSE (G)",
        "RMSE_over_sigma_HR": r"RMSE / $\sigma_{HR}$",
        "CC": "Correlation coefficient",
        "R2": r"$R^2$",
        "SSIM": "SSIM",
        "PSNR_dB": "PSNR (dB)",
        "net_flux_ratio": r"$\Phi_{net}/\Phi_{net,HR}$",
        "unsigned_flux_ratio": r"$\Phi_{uns}/\Phi_{uns,HR}$",
    }
    fig, axes = plt.subplots(3, 3, figsize=(14, 12))
    y_position = np.arange(len(MODEL_ORDER))

    for axis, metric in zip(axes.flat, METRIC_ORDER):
        means, stds = [], []
        for model in MODEL_ORDER:
            model_data = subset[subset["model"] == model]
            mean, std = finite_mean_std(model_data[metric])
            means.append(mean)
            stds.append(std)
        axis.barh(
            y_position,
            means,
            xerr=stds,
            capsize=3,
            color=[MODEL_COLORS[model] for model in MODEL_ORDER],
        )
        axis.set_yticks(y_position, MODEL_ORDER)
        axis.invert_yaxis()
        axis.set_title(titles[metric])
        axis.grid(axis="x", alpha=0.3)
        if metric in {"CC", "R2", "SSIM"}:
            axis.set_xlim(0, 1)
        elif metric in {"net_flux_ratio", "unsigned_flux_ratio"}:
            axis.set_xlim(0, 2)

    fig.suptitle(f"{category}: {num_samples} test samples", fontsize=16)
    fig.tight_layout()
    if output_path is not None:
        fig.savefig(output_path, dpi=200, bbox_inches="tight")
    if show:
        plt.show()
    plt.close(fig)


def save_category(
    long_table: pd.DataFrame,
    sample_mask: np.ndarray,
    category: str,
    dataset_type: str,
    output_dir: Path,
    save: bool,
    show: bool,
) -> None:
    selected_indices = set(long_table.loc[sample_mask, "sample_idx"].astype(int))
    subset = long_table[long_table["sample_idx"].isin(selected_indices)].copy()
    num_samples = len(selected_indices)
    if not num_samples:
        print(f"Skipped empty category: {category}")
        return

    numeric_table, formatted_table = build_summary_table(subset)
    safe_category = category.replace("/", "-")
    stem = f"eval_{dataset_type}_{safe_category}_num.{num_samples}"

    print(f"\n[{category}] {num_samples} samples")
    print(formatted_table.to_string(index=False))

    figure_path = output_dir / f"{stem}.png" if save else None
    plot_summary(subset, category, num_samples, figure_path, show)

    if save:
        wide_detail = subset.pivot(
            index=["prediction_file", "sample_idx", "theta_deg", "region_type"],
            columns="model",
            values=METRIC_ORDER,
        )
        wide_detail.columns = [f"{metric}_{model}" for metric, model in wide_detail.columns]
        wide_detail.reset_index().to_csv(
            output_dir / f"{stem}_samples.csv", index=False, encoding="utf-8-sig"
        )
        numeric_table.to_csv(
            output_dir / f"{stem}_table_numeric.csv", index=False, encoding="utf-8-sig"
        )
        formatted_table.to_csv(
            output_dir / f"{stem}_table.csv", index=False, encoding="utf-8-sig"
        )
        write_text_summary(
            output_dir / f"{stem}.txt", category, num_samples, numeric_table
        )
        print(f"Saved category outputs with prefix: {output_dir / stem}")


def main() -> None:
    args = parse_args()
    prediction_dir = args.run_dir / f"{args.dataset_type}_pred"
    files = sorted(prediction_dir.glob("*.npz"), key=natural_key)
    if not files:
        raise FileNotFoundError(f"No NPZ predictions found in {prediction_dir}")

    records = []
    for index, path in enumerate(files, start=1):
        records.extend(evaluate_one(path))
        if index % 200 == 0 or index == len(files):
            print(f"Evaluated samples: {index}/{len(files)}")
    long_table = pd.DataFrame(records)

    classification_path = (
        args.classification_file
        or args.run_dir / f"{args.dataset_type}_sample_classification.csv"
    )
    classification = load_classification(classification_path)
    long_table = long_table.merge(classification, on="sample_idx", how="left", validate="many_to_one")
    if long_table["region_type"].isna().any():
        missing = sorted(long_table.loc[long_table["region_type"].isna(), "sample_idx"].unique())
        raise ValueError(f"Missing AR classification for sample_idx values: {missing[:20]}")

    sample_table = (
        long_table[["sample_idx", "theta_deg", "region_type"]]
        .drop_duplicates("sample_idx")
        .sort_values("sample_idx")
        .reset_index(drop=True)
    )
    categories = make_categories(sample_table)
    output_dir = args.output_dir or args.run_dir
    save = not args.no_save
    if save:
        output_dir.mkdir(parents=True, exist_ok=True)

    for category, mask in categories.items():
        selected_sample_idx = set(sample_table.loc[mask, "sample_idx"].astype(int))
        long_mask = long_table["sample_idx"].isin(selected_sample_idx).to_numpy()
        save_category(
            long_table,
            long_mask,
            category,
            args.dataset_type,
            output_dir,
            save,
            args.show,
        )


if __name__ == "__main__":
    main()
